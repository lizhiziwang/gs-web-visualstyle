#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
从 HTML 模板自动生成 Wicket .properties 资源文件。

必要性：
  1. Wicket 10 的 <wicket:message key="..."> 在词条缺失时会直接抛
     WicketRuntimeException（"Property 'X' not found in property files"），
     并不使用标签内的文本作为兜底 —— 因此每个 key 都必须存在。
  2. Java properties 规范按 ISO-8859-1 读取，中文必须写成 \\uXXXX 转义，
     否则页面上会出现乱码（GeoServer 自身也是这么做的）。

用法：
    python tools/gen_properties.py
"""

import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "gs-web-visualstyle" / "src" / "main" / "resources"

MSG_RE = re.compile(
    r'<wicket:message\s+key="([^"]+)"\s*>(.*?)</wicket:message>', re.S
)


def esc_key(key: str) -> str:
    """properties 里 key 中的 : = 空格 需要转义。"""
    out = []
    for ch in key:
        if ch in ":= ":
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def esc_value(value: str) -> str:
    """把值转成 ISO-8859-1 安全的 \\uXXXX 形式。"""
    value = re.sub(r"\s+", " ", value).strip()
    out = []
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch in "\t\n\r\f":
            out.append("\\" + {"\t": "t", "\n": "n", "\r": "r", "\f": "f"}[ch])
        elif code < 0x20 or code > 0x7E:
            out.append("\\u%04x" % code)
        else:
            out.append(ch)
    return "".join(out)


def process(html: Path) -> int:
    text = html.read_text(encoding="utf-8")
    pairs = MSG_RE.findall(text)
    if not pairs:
        return 0
    props = html.with_suffix(".properties")

    # 保留已有（人工维护的）词条，自动生成的词条覆盖同名项
    existing = {}
    if props.is_file():
        for line in props.read_text(encoding="latin-1").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, _, v = line.partition("=")
            existing[k.strip()] = v.strip()

    for key, body in pairs:
        existing[esc_key(key)] = esc_value(body)

    lines = [
        "# AUTO-GENERATED by tools/gen_properties.py from the sibling HTML template.",
        "# Entries come from wicket:message tags in the markup.",
        "# Non-ASCII text is escaped as backslash-uXXXX (properties are read as ISO-8859-1).",
        "",
    ]
    for k in sorted(existing):
        lines.append("%s = %s" % (k, existing[k]))
    lines.append("")

    props.write_text("\n".join(lines), encoding="latin-1")
    return len(pairs)


def main():
    total = 0
    files = 0
    for html in sorted(RES.rglob("*.html")):
        n = process(html)
        if n:
            total += n
            files += 1
            print("  %-62s %d 条" % (html.relative_to(RES), n))
    print("-" * 78)
    print("已处理 %d 个模板，共 %d 条词条。" % (files, total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
